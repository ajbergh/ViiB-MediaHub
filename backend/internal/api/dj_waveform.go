// errClientWaveformRequired marks formats which the browser can decode but the
// server intentionally does not decode. Callers should fall back to Web Audio.
var errClientWaveformRequired = errors.New("client-side waveform generation required")

// WaveformResponse contains the waveform peak data for a track.
type WaveformResponse struct {
	TrackID    string    `json:"trackId"`
	Duration   float64   `json:"duration"`   // Total duration in seconds
	SampleRate int       `json:"sampleRate"` // Source sample rate
	Resolution int       `json:"resolution"` // Samples per peak (e.g., 256)
	Peaks      []float64 `json:"peaks"`      // Normalized peak values (0-1)
}

// HotCue represents a saved position in a track.
type HotCue struct {
	Slot              int      `json:"slot"`     // 1-8
	Position          float64  `json:"position"` // Position in seconds
	Label             string   `json:"label,omitempty"`
	Color             string   `json:"color"` // Hex color code
	Origin            string   `json:"origin,omitempty"`
	GeneratorVersion  string   `json:"generatorVersion,omitempty"`
	Confidence        *float64 `json:"confidence,omitempty"`
	Kind              string   `json:"kind,omitempty"`
	Locked            bool     `json:"locked,omitempty"`
	Rationale         string   `json:"rationale,omitempty"`
	SourceFingerprint string   `json:"sourceFingerprint,omitempty"`
	DownbeatAligned   bool     `json:"downbeatAligned,omitempty"`
	UpdatedAt         int64    `json:"updatedAt,omitempty"`
}

// HotCuesResponse contains hot cue data for a track.
type HotCuesResponse struct {
	TrackID string   `json:"trackId"`
	HotCues []HotCue `json:"hotCues"`
}

type djWaveformOutcome struct {
	status     int
	errMsg     string
	capability *audio.CapabilityError
	response   WaveformResponse
}

type djWaveformFlight struct {
	done    chan struct{}
	cancel  context.CancelFunc
	waiters int
	outcome djWaveformOutcome
}

// getDJWaveform generates or returns cached waveform data for a track.
// GET /api/dj/waveform/{id}
func (a *API) getDJWaveform(w http.ResponseWriter, r *http.Request) {
	trackID := chi.URLParam(r, "id")
	if trackID == "" {
		respondError(w, http.StatusBadRequest, "Track ID required")
		return
	}

	// Legacy song-ID-only caches cannot prove current source identity.
	source, err := a.resolveAnalysisSource(r.Context(), trackID)
	if err != nil {
		respondError(w, 404, "Track source unavailable")
		return
	}
	if !waveformDecoders().Supports(source.Name) {
		capErr := audio.NewWaveformCapabilityError(source.Name)
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(http.StatusUnprocessableEntity)
		_ = json.NewEncoder(w).Encode(map[string]any{
			"error":      "Waveform will be generated by the client for this audio format",
			"capability": capErr,
		})
		return
	}
	if resp, ok, conflict := a.tryCachedDJWaveform(r.Context(), trackID, source.Fingerprint); conflict {
		respondError(w, 409, "Track source changed while reading waveform")
		return
	} else if ok {
		respondJSON(w, resp)
		return
	}

	outcome, err := a.shareDJWaveform(r.Context(), trackID, source)
	if err != nil {
		return
	}
	if outcome.status == http.StatusOK {
		respondJSON(w, outcome.response)
		return
	}
	if outcome.capability != nil {
		w.Header().Set("Content-Type", "application/json")
		w.WriteHeader(outcome.status)
		_ = json.NewEncoder(w).Encode(map[string]any{
			"error":      outcome.errMsg,
			"capability": outcome.capability,
		})
		return
	}
	respondError(w, outcome.status, outcome.errMsg)
}

func (a *API) tryCachedDJWaveform(ctx context.Context, trackID, fingerprint string) (WaveformResponse, bool, bool) {
	if fingerprint == "" {
		return WaveformResponse{}, false, false
	}
	artifact, err := a.db.GetTrackAnalysisArtifactBounded(trackID, waveformartifact.Kind, waveformartifact.FormatVersion, waveformartifact.AlgorithmVersion, waveformartifact.MaxBytes)
	if err != nil || artifact.SourceFingerprint != fingerprint || artifact.Encoding != waveformartifact.Encoding || artifact.Provenance != "measured" {
		return WaveformResponse{}, false, false
	}
	overview, err := waveformartifact.Decode(artifact.Data)
	if err != nil {
		return WaveformResponse{}, false, false
	}
	current, resolveErr := a.resolveAnalysisSource(ctx, trackID)
	if resolveErr != nil || current.Fingerprint != fingerprint {
		return WaveformResponse{}, false, true
	}
	return WaveformResponse{
		TrackID:    trackID,
		Duration:   overview.Duration(),
		SampleRate: overview.SampleRate,
		Resolution: overview.Resolution,
		Peaks:      overview.Peaks,
	}, true, false
}

func (a *API) shareDJWaveform(ctx context.Context, trackID string, source analysis.ResolvedSource) (djWaveformOutcome, error) {
	if err := ctx.Err(); err != nil {
		return djWaveformOutcome{}, err
	}
	key := trackID + "\x00" + source.Fingerprint
	a.djWaveformMu.Lock()
	if a.djWaveformFlights == nil {
		a.djWaveformFlights = make(map[string]*djWaveformFlight)
	}
	f := a.djWaveformFlights[key]
	if f == nil {
		work, cancel := context.WithCancel(context.Background())
		f = &djWaveformFlight{done: make(chan struct{}), cancel: cancel}
		a.djWaveformFlights[key] = f
		go func(f *djWaveformFlight) {
			outcome := a.computeOrWaitDJWaveform(work, trackID, source)
			cancel()
			a.djWaveformMu.Lock()
			f.outcome = outcome
			if a.djWaveformFlights[key] == f {
				delete(a.djWaveformFlights, key)
			}
			close(f.done)
			a.djWaveformMu.Unlock()
		}(f)
	}
	f.waiters++
	a.djWaveformMu.Unlock()

	select {
	case <-f.done:
		if err := ctx.Err(); err != nil {
			return djWaveformOutcome{}, err
		}
		return f.outcome, nil
	case <-ctx.Done():
		a.djWaveformMu.Lock()
		if a.djWaveformFlights[key] == f {
			f.waiters--
			if f.waiters == 0 {
				delete(a.djWaveformFlights, key)
				f.cancel()
			}
		}
		a.djWaveformMu.Unlock()
		return djWaveformOutcome{}, ctx.Err()
	}
}

func (a *API) computeOrWaitDJWaveform(ctx context.Context, trackID string, source analysis.ResolvedSource) djWaveformOutcome {
	const (
		initialBackoff = 50 * time.Millisecond
		maxBackoff     = 400 * time.Millisecond
	)
	// Read again after winning ownership: a previous owner may have published
	// between the initial miss and this claim. Waiters never open the audio.
	var token string
	backoff := initialBackoff
	for {
		if resp, ok, conflict := a.tryCachedDJWaveform(ctx, trackID, source.Fingerprint); conflict {
			if token != "" {
				_ = a.db.ReleaseWaveformLease(trackID, token)
			}
			return djWaveformOutcome{status: 409, errMsg: "Track source changed while reading waveform"}
		} else if ok {
			if token != "" {
				_ = a.db.ReleaseWaveformLease(trackID, token)
			}
			return djWaveformOutcome{status: http.StatusOK, response: resp}
		}
		if token != "" {
			break
		}
		var claimed bool
		var err error
		token, claimed, err = a.db.ClaimWaveformLease(trackID, source.Fingerprint)
		if err != nil {
			return djWaveformOutcome{status: 500, errMsg: "Waveform coordination failed"}
		}
		if claimed {
			continue
		}
		wait := backoff*3/4 + rand.N(backoff/2+1)
		timer := time.NewTimer(wait)
		select {
		case <-ctx.Done():
			timer.Stop()
			return djWaveformOutcome{status: http.StatusRequestTimeout, errMsg: "Waveform request canceled"}
		case <-timer.C:
		}
		backoff *= 2
		if backoff > maxBackoff {
			backoff = maxBackoff
		}
		current, resolveErr := a.resolveAnalysisSource(ctx, trackID)
		if resolveErr != nil || current.Fingerprint != source.Fingerprint {
			return djWaveformOutcome{status: 409, errMsg: "Track source changed during waveform generation"}
		}
	}

	leaseCtx, stop := maintainWaveformLease(ctx, a.db, trackID, source.Fingerprint, token)
	defer func() { stop(); _ = a.db.ReleaseWaveformLease(trackID, token) }()
	leaderSource, err := a.resolveAnalysisSource(leaseCtx, trackID)
	if err != nil || leaderSource.Fingerprint != source.Fingerprint || leaseCtx.Err() != nil {
		return djWaveformOutcome{status: 409, errMsg: "Track source changed during waveform generation"}
	}
	overview, decodeErr := analysis.GenerateWaveformOverviewWithOpener(leaseCtx, waveformDecoders(), leaderSource.Name, leaderSource.Open, analysis.DefaultWaveformResolution)
	waveform, err := djWaveformFromOverview(overview, decodeErr, leaderSource.Name)
	if err != nil {
		if errors.Is(err, errClientWaveformRequired) {
			capErr := audio.NewWaveformCapabilityError(leaderSource.Name)
			return djWaveformOutcome{
				status:     http.StatusUnprocessableEntity,
				errMsg:     "Waveform will be generated by the client for this audio format",
				capability: capErr,
			}
		}
		return djWaveformOutcome{status: 500, errMsg: "Waveform generation failed"}
	}
	current, err := a.resolveAnalysisSource(leaseCtx, trackID)
	if err != nil || current.Fingerprint != source.Fingerprint || leaseCtx.Err() != nil {
		return djWaveformOutcome{status: 409, errMsg: "Track source changed during waveform generation"}
	}
	encoded, err := waveformartifact.Encode(overview)
	if err != nil {
		return djWaveformOutcome{status: 500, errMsg: "Waveform validation failed"}
	}
	if err = a.db.PublishWaveformLease(token, db.TrackAnalysisArtifact{ID: trackID + ":" + waveformartifact.AlgorithmVersion, SongID: trackID, Kind: waveformartifact.Kind, FormatVersion: waveformartifact.FormatVersion, AlgorithmVersion: waveformartifact.AlgorithmVersion, Encoding: waveformartifact.Encoding, Provenance: "measured", SourceFingerprint: source.Fingerprint, Data: encoded}); err != nil {
		logger.API("DJ waveform: artifact persistence failed for %s", trackID)
		return djWaveformOutcome{status: 409, errMsg: "Waveform ownership changed during generation"}
	}

	current, err = a.resolveAnalysisSource(leaseCtx, trackID)
	if err != nil || current.Fingerprint != source.Fingerprint || leaseCtx.Err() != nil {
		return djWaveformOutcome{status: 409, errMsg: "Track source changed during waveform generation"}
	}
	return djWaveformOutcome{
		status: http.StatusOK,
		response: WaveformResponse{
			TrackID:    trackID,
			Duration:   waveform.Duration,
			SampleRate: waveform.SampleRate,
			Resolution: waveform.Resolution,
			Peaks:      waveform.Peaks,
		},
	}
}

// getDJHotCues returns hot cue points for a track.
// GET /api/dj/hotcues/{id}
func (a *API) getDJHotCues(w http.ResponseWriter, r *http.Request) {
	trackID := chi.URLParam(r, "id")
	if trackID == "" {
		respondError(w, http.StatusBadRequest, "Track ID required")
		return
	}

	hotCues, err := a.db.GetDJHotCues(trackID)
	if err != nil {
		logger.API("DJ hot cues: failed to get for %s: %v", trackID, err)
		respondError(w, http.StatusInternalServerError, "Failed to get hot cues")
		return
	}

	response := HotCuesResponse{
		TrackID: trackID,
		HotCues: make([]HotCue, 0, len(hotCues)),
	}

	for _, hc := range hotCues {
		response.HotCues = append(response.HotCues, HotCue{
			Slot:              hc.Slot,
			Position:          hc.Position,
			Label:             hc.Label,
			Color:             hc.Color,
			Origin:            hc.Origin,
			GeneratorVersion:  hc.GeneratorVersion,
			Confidence:        hc.Confidence,
			Kind:              hc.Kind,
			Locked:            hc.Locked,
			Rationale:         hc.Rationale,
			SourceFingerprint: hc.SourceFingerprint,
			DownbeatAligned:   hc.DownbeatAligned,
			UpdatedAt:         hc.UpdatedAt,
		})
	}

	respondJSON(w, response)
}

// saveDJHotCues saves hot cue points for a track.
// PUT /api/dj/hotcues/{id}
func (a *API) saveDJHotCues(w http.ResponseWriter, r *http.Request) {
	trackID := chi.URLParam(r, "id")
	if trackID == "" {
		respondError(w, http.StatusBadRequest, "Track ID required")
		return
	}

	var req HotCuesResponse
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		respondError(w, http.StatusBadRequest, "Invalid request body")
		return
	}

	// Convert to database format
	dbHotCues := make([]db.DJHotCue, 0, len(req.HotCues))
	seenSlots := make(map[int]struct{}, len(req.HotCues))
	for _, hc := range req.HotCues {
		if hc.Slot < 1 || hc.Slot > 8 {
			respondError(w, http.StatusBadRequest, "Hot cue slots must be between 1 and 8")
			return
		}
		if _, exists := seenSlots[hc.Slot]; exists {
			respondError(w, http.StatusBadRequest, "Hot cue slots must be unique")
			return
		}
		seenSlots[hc.Slot] = struct{}{}
		if hc.Origin != "" && hc.Origin != "user" && hc.Origin != "analysis" {
			respondError(w, http.StatusBadRequest, "Hot cue origin must be user or analysis")
			return
		}
		if hc.Origin == "" {
			hc.Origin = "user"
		}
		if hc.Origin == "analysis" && hc.DownbeatAligned && hc.Rationale != "qualified-measured-downbeat" && hc.Rationale != "qualified-manual-downbeat" {
			respondError(w, http.StatusBadRequest, "Analysis cue downbeat alignment requires measured or manual provenance")
			return
		}
		dbHotCues = append(dbHotCues, db.DJHotCue{
			Slot:              hc.Slot,
			Position:          hc.Position,
			Label:             hc.Label,
			Color:             hc.Color,
			Origin:            hc.Origin,
			GeneratorVersion:  hc.GeneratorVersion,
			Confidence:        hc.Confidence,
			Kind:              hc.Kind,
			Locked:            hc.Locked,
			Rationale:         hc.Rationale,
			SourceFingerprint: hc.SourceFingerprint,
			DownbeatAligned:   hc.DownbeatAligned,
			UpdatedAt:         hc.UpdatedAt,
		})
	}

	if err := a.db.SaveDJHotCues(trackID, dbHotCues); err != nil {
		logger.API("DJ hot cues: failed to save for %s: %v", trackID, err)
		respondError(w, http.StatusInternalServerError, "Failed to save hot cues")
		return
	}

	respondJSON(w, map[string]bool{"success": true})
}

// waveformDecoders is the shared analysis decoder registry. Server-side
// waveform support is therefore exactly the backend codec capability matrix,
// not a second hand-maintained switch that can drift from it.
var waveformDecoders = sync.OnceValue(analysis.NewDefaultDecoderRegistry)

// generateWaveform generates peak data from an audio file.
// Returns normalized peak values (0-1) at specified resolution.
//
// Decoding, downmixing, and chunk bounds are owned by internal/analysis, so
// the waveform overview, tempo, and key all read one PCM implementation.
// Formats with no backend decoder return errClientWaveformRequired and are
// deferred to Web Audio in the renderer.
func generateWaveform(filePath string) (*db.DJWaveform, error) {
	return generateWaveformWith(context.Background(), waveformDecoders(), filePath)
}

func generateWaveformWith(ctx context.Context, registry *analysis.DecoderRegistry, filePath string) (*db.DJWaveform, error) {
	overview, err := analysis.GenerateWaveformOverview(ctx, registry, filePath, analysis.DefaultWaveformResolution)
	return djWaveformFromOverview(overview, err, filePath)
}

func djWaveformFromOverview(overview analysis.WaveformOverview, err error, name string) (*db.DJWaveform, error) {
	if err != nil {
		if errors.Is(err, analysis.ErrUnsupportedCodec) {
			// Report the format that was refused so the fallback is auditable.
			extension := strings.TrimPrefix(strings.ToLower(filepath.Ext(name)), ".")
			if extension == "" {
				extension = "unknown"
			}
			return nil, fmt.Errorf("%w: %s format", errClientWaveformRequired, extension)
		}
		return nil, err
	}
	return &db.DJWaveform{
		Duration:   overview.Duration(),
		SampleRate: overview.SampleRate,
		Resolution: overview.Resolution,
		Peaks:      overview.Peaks,
	}, nil
}

func maintainWaveformLease(parent context.Context, database *db.DB, song, fp, token string) (context.Context, func()) {
	ctx, cancel := context.WithCancel(parent)
	done := make(chan struct{})
	go func() {
		defer close(done)
		ticker := time.NewTicker(time.Duration(db.TrackAnalysisLeaseMillis/3) * time.Millisecond)
		defer ticker.Stop()
		for {
			select {
			case <-ctx.Done():
				return
			case <-ticker.C:
				if database.RenewWaveformLease(song, fp, token) != nil {
					cancel()
					return
				}
			}
		}
	}()
	var once sync.Once
	return ctx, func() { once.Do(func() { cancel(); <-done }) }
}
